#!/usr/bin/env bash
# ════════════════════════════════════════════════════════════════════════════
#  Dual-monitor helper for Hyprland — extend / mirror / single output / GUI.
#  Everything is applied LIVE via the Hyprland Lua API (no relogin).
#
#    monitor.sh menu              wofi menu (default)
#    monitor.sh extend [right|left|up|down]
#    monitor.sh mirror            landscape mirror with supported display modes
#    monitor.sh internal          laptop panel only  (external off)
#    monitor.sh external          external only      (laptop off)
#    monitor.sh gui               open nwg-displays (GNOME-like: drag/rotate/scale)
#
#  Presets and the GUI save monitors.conf; previous layouts are backed up.
# ════════════════════════════════════════════════════════════════════════════
set -u

note() { notify-send -a Monitor "Monitor" "$1" 2>/dev/null || true; printf '%s\n' "$1"; }

# All monitors incl. disabled ones (so we can re-enable them).
mons() { hyprctl monitors all -j; }

# Print "INTERNAL EXTERNAL" (external empty if only one monitor).
read_names() {
    mons | python3 -c '
import json,sys,re
d=json.load(sys.stdin)
intn=next((m["name"] for m in d if re.match(r"(eDP|LVDS|DSI)",m["name"],re.I)), None)
if intn is None and d: intn=d[0]["name"]
ext=next((m["name"] for m in d if m["name"]!=intn), "")
print(intn or "", ext)'
}

# Same resolution with the closest supported refresh rates on both outputs.
common_modes() { # args: INTERNAL EXTERNAL -> "internal-mode external-mode"
    mons | python3 -c '
import json,sys,re
d=json.load(sys.stdin); intn,ext=sys.argv[1],sys.argv[2]
def modes(name):
    r={}
    for m in d:
        if m["name"]==name:
            for s in m.get("availableModes",[]):
                mm=re.match(r"(\d+)x(\d+)@([\d.]+)Hz",s)
                if mm:
                    w,h,hz=int(mm.group(1)),int(mm.group(2)),round(float(mm.group(3)),2)
                    r.setdefault((w,h),set()).add(hz)
    return r
mi,me=modes(intn),modes(ext)
common=[k for k in mi if k in me]
if not common:
    print("preferred preferred")
    sys.exit(0)
w,h=max(common,key=lambda k:k[0]*k[1])
# Never send the laptop-only refresh rate to a TV that cannot display it.
internal_rate,external_rate=min(((a,b) for a in mi[(w,h)] for b in me[(w,h)]),
                               key=lambda pair:(abs(pair[0]-pair[1]),-min(pair),-max(pair)))
print(f"{w}x{h}@{internal_rate:.2f}Hz {w}x{h}@{external_rate:.2f}Hz")' "$1" "$2"
}

apply() {
    # Apply the whole preset together; explicitly clear obsolete mirror/rotation
    # fields. hl.monitor merges fields, so omitted settings remain active.
    if ! python3 - "$@" <<'PY'
from datetime import datetime
import json, os
from pathlib import Path
import shutil, subprocess, sys, tempfile

numeric = {'transform', 'vrr', 'bitdepth', 'sdrbrightness', 'sdrsaturation'}
extras = numeric | {'mirror', 'cm'}
def parse(value):
    parts = [part.strip() for part in value.split(',')]
    spec = {'output': parts[0]}
    if parts[1] == 'disable':
        return dict(spec, disabled=True)
    if parts[1] in extras:
        index = 1
    else:
        spec.update(mode=parts[1], position=parts[2], scale=float(parts[3]), disabled=False)
        index = 4
    if (len(parts)-index) % 2:
        raise ValueError('Incomplete monitor option')
    for key, value in zip(parts[index::2], parts[index+1::2]):
        if key not in extras:
            raise ValueError('Unsupported monitor option: ' + key)
        if key in {'transform', 'vrr', 'bitdepth'}:
            number = float(value)
            if not number.is_integer():
                raise ValueError('Expected an integer for ' + key)
            spec[key] = int(number)
        else:
            spec[key] = float(value) if key in numeric else value
    return spec

def lua(value):
    if isinstance(value, bool):
        return 'true' if value else 'false'
    return json.dumps(value, ensure_ascii=False)

config = Path(os.environ.get('XDG_CONFIG_HOME', Path.home()/'.config'))/'hypr/monitors.conf'
lines = config.read_text().splitlines() if config.exists() else []
updates = [parse(arg) for arg in sys.argv[1:]]
outputs = {spec['output'] for spec in updates}
saved = {spec['output']: {} for spec in updates}
kept = []
for line in lines:
    key, separator, value = line.partition('=')
    if separator and key.strip() == 'monitor' and value.split(',')[0].strip() in outputs:
        previous = parse(value.split('#')[0].strip())
        saved[previous['output']].update(previous)
    elif line.startswith('# Generated by nwg-displays'):
        kept.append('# Updated by monitor.sh. Manage with Super+O or nwg-displays.')
    else:
        kept.append(line)
statements = []
for spec in updates:
    saved[spec['output']].update(spec)
    statements.append('hl.monitor({' + ','.join(key+'='+lua(value) for key,value in spec.items()) + '})')
result = subprocess.run(['hyprctl', 'eval', ';'.join(statements)], capture_output=True, text=True)
if result.returncode or result.stdout.strip() != 'ok':
    raise SystemExit(result.stderr.strip() or result.stdout.strip() or 'Hyprland rejected the layout')

# Replace all old entries for these outputs, including separate transform lines.
# Retain display options such as HDR/VRR and entries for unrelated outputs.
for spec in saved.values():
    fields = [spec['output']]
    if spec.get('disabled'):
        fields.append('disable')
    else:
        fields.extend([spec['mode'], spec['position'], str(spec['scale'])])
    # nwg-displays reads the final comma-separated field as the mirror target.
    option_keys = sorted((extras & spec.keys()) - {'mirror'})
    if 'mirror' in spec:
        option_keys.append('mirror')
    for key in option_keys:
        # Disabled outputs can retain their options in a separate config entry.
        if spec.get('disabled'):
            kept.append('monitor=' + ','.join([spec['output'], key, str(spec[key])]))
        else:
            fields.extend([key, str(spec[key])])
    kept.append('monitor=' + ','.join(fields))
content = '\n'.join(kept).rstrip() + '\n'
if config.exists() and content == config.read_text():
    raise SystemExit(0)
config.parent.mkdir(parents=True, exist_ok=True)
if config.exists():
    backup = Path(os.environ.get('XDG_CACHE_HOME', Path.home()/'.cache'))/'dotfiles/backups'
    backup.mkdir(parents=True, exist_ok=True)
    shutil.copy2(config, backup/('monitors-' + datetime.now().strftime('%Y%m%d-%H%M%S-%f') + '.conf'))
fd, temporary = tempfile.mkstemp(prefix='.monitors-', dir=config.parent)
try:
    with os.fdopen(fd, 'w') as file:
        file.write(content)
    os.replace(temporary, config)
finally:
    Path(temporary).unlink(missing_ok=True)
PY
    then
        note "Gagal menerapkan/menyimpan layout monitor. Cek pesan error di terminal."
        return 1
    fi
}

read -r INT EXT < <(read_names)
[[ -n "$INT" ]] || { note "Tidak ada monitor yang bisa diatur."; exit 1; }

need_external() {
    if [ -z "$EXT" ]; then
        note "Cuma 1 monitor terdeteksi ($INT). Colok monitor eksternal dulu."
        exit 0
    fi
}

case "${1:-menu}" in
    extend)
        need_external
        case "${2:-right}" in
            left)  pos="auto-left"  ;;
            up)    pos="auto-up"    ;;
            down)  pos="auto-down"  ;;
            *)     pos="auto-right" ;;
        esac
        apply "$INT, preferred, 0x0, 1, mirror," \
              "$EXT, preferred, $pos, 1, mirror," || exit 1
        note "Extend: $EXT di sebelah ${2:-right} dari $INT"
        ;;

    mirror)
        need_external
        read -r imode emode < <(common_modes "$INT" "$EXT") || exit 1
        apply "$INT, $imode, 0x0, 1, transform,0, vrr,0, mirror," \
              "$EXT, $emode, 0x0, 1, transform,0, vrr,0, mirror,$INT" || exit 1
        note "Mirror landscape: $INT ($imode) → $EXT ($emode)"
        ;;

    internal)
        specs=("$INT, preferred, 0x0, 1, mirror,")
        [[ -z "$EXT" ]] || specs+=("$EXT, disable")
        apply "${specs[@]}" || exit 1
        note "Laptop saja: $INT (eksternal dimatikan)"
        ;;

    external)
        need_external
        apply "$EXT, preferred, 0x0, 1, mirror," "$INT, disable" || exit 1
        note "Eksternal saja: $EXT (laptop dimatikan)"
        ;;

    gui)
        if command -v nwg-displays >/dev/null; then
            exec nwg-displays -m "$HOME/.config/hypr/monitors.conf" \
                              -w "$HOME/.config/hypr/workspaces.conf"
        else
            note "nwg-displays belum terpasang. Install: yay -S nwg-displays"
        fi
        ;;

    menu)
        sel=$(printf '%s\n' \
            "Extend — eksternal di kanan" \
            "Extend — eksternal di kiri" \
            "Mirror — samakan resolusi" \
            "Laptop saja" \
            "Eksternal saja" \
            "Atur manual — drag / putar / skala (GUI)" \
            | wofi --dmenu -i -p "Monitor")
        case "$sel" in
            *kanan*)     exec "$0" extend right ;;
            *kiri*)      exec "$0" extend left ;;
            Mirror*)     exec "$0" mirror ;;
            "Laptop saja") exec "$0" internal ;;
            "Eksternal saja") exec "$0" external ;;
            *GUI*)       exec "$0" gui ;;
        esac
        ;;

    *)
        echo "usage: monitor.sh {menu|extend [right|left|up|down]|mirror|internal|external|gui}" >&2
        exit 2
        ;;
esac
