#!/usr/bin/env bash
# ════════════════════════════════════════════════════════════════════════════
#  Sleep & idle manager for Hyprland — a front-end for hypridle.
#
#    idle.sh menu             wofi GUI: presets + toggles      (SUPER+ALT+I)
#    idle.sh tui              interactive editor in a terminal
#    idle.sh status           print the active timings
#    idle.sh set KEY VALUE    set one value and re-apply
#    idle.sh apply            regenerate hypridle.conf + restart hypridle
#    idle.sh maybe-suspend    internal — honours "stay awake on AC"
#
#  Source of truth is ~/.config/hypr/idle.conf (machine-local, gitignored).
#  hypridle.conf is GENERATED from it — never edit hypridle.conf by hand.
# ════════════════════════════════════════════════════════════════════════════
set -u

SELF="$HOME/.local/bin/idle.sh"
[ -x "$SELF" ] || SELF="$(readlink -f "${BASH_SOURCE[0]}")"

HYPR="$HOME/.config/hypr"
CONF="$HYPR/idle.conf"
DEFAULT="$HYPR/idle.conf.default"
OUT="$HYPR/hypridle.conf"

note() { notify-send -a Idle "󰒲  Sleep & Idle" "$1" 2>/dev/null || true; printf '%s\n' "$1"; }

# ── defaults (minutes; 0 = disabled) ────────────────────────────────────────
LOCK=10
SCREEN_OFF=12
SUSPEND=30
SUSPEND_ON_AC=0        # 1 = also suspend while plugged in

is_num() { [[ "${1:-}" =~ ^[0-9]+$ ]]; }

load() {
    if [ ! -f "$CONF" ] && [ -f "$DEFAULT" ]; then cp "$DEFAULT" "$CONF"; fi
    if [ -f "$CONF" ]; then
        # only take the four keys we own — ignore anything else in the file
        local k v
        while IFS='=' read -r k v; do
            k="${k// /}"; v="${v%%#*}"; v="${v// /}"
            case "$k" in
                LOCK|SCREEN_OFF|SUSPEND|SUSPEND_ON_AC) is_num "$v" && printf -v "$k" '%s' "$v" ;;
            esac
        done < <(grep -E '^[[:space:]]*[A-Z_]+[[:space:]]*=' "$CONF")
    fi
}

save() {
    mkdir -p "$HYPR"
    {
        echo "# ── Sleep & idle settings ───────────────────────────────────────────────"
        echo "# Values are MINUTES. 0 = disabled."
        echo "# Edit with:  SUPER+ALT+I  (GUI)   ·   idle.sh tui   ·   idle.sh set KEY VAL"
        echo "# hypridle.conf is generated from this file — don't edit it directly."
        echo
        printf '%-24s # %s\n' "LOCK=$LOCK"                   "lock the screen after N minutes idle"
        printf '%-24s # %s\n' "SCREEN_OFF=$SCREEN_OFF"       "turn the display off after N minutes idle"
        printf '%-24s # %s\n' "SUSPEND=$SUSPEND"             "suspend (sleep) after N minutes idle"
        printf '%-24s # %s\n' "SUSPEND_ON_AC=$SUSPEND_ON_AC" "1 = suspend even when plugged in, 0 = stay awake on AC"
    } > "$CONF"
}

# ── generate hypridle.conf ──────────────────────────────────────────────────
gen() {
    mkdir -p "$HYPR"
    {
        echo "# ╔══════════════════════════════════════════════════════════════════╗"
        echo "# ║  GENERATED by idle.sh — edit ~/.config/hypr/idle.conf instead.   ║"
        echo "# ║  Regenerate: idle.sh apply     ·     GUI: SUPER+ALT+I            ║"
        echo "# ╚══════════════════════════════════════════════════════════════════╝"
        echo
        echo "general {"
        echo "    lock_cmd = pidof hyprlock || hyprlock       # never stack lockers"
        echo "    before_sleep_cmd = loginctl lock-session    # lock before suspend"
        echo "    after_sleep_cmd = hyprctl dispatch dpms on  # screen back on"
        echo "    ignore_dbus_inhibit = false                 # respect video players etc."
        echo "    ignore_systemd_inhibit = false"
        echo "}"

        if [ "$LOCK" -gt 0 ]; then
            echo
            echo "# lock after ${LOCK}m"
            echo "listener {"
            echo "    timeout = $((LOCK * 60))"
            echo "    on-timeout = loginctl lock-session"
            echo "}"
        fi

        if [ "$SCREEN_OFF" -gt 0 ]; then
            echo
            echo "# display off after ${SCREEN_OFF}m"
            echo "listener {"
            echo "    timeout = $((SCREEN_OFF * 60))"
            echo "    on-timeout = hyprctl dispatch dpms off"
            echo "    on-resume  = hyprctl dispatch dpms on"
            echo "}"
        fi

        if [ "$SUSPEND" -gt 0 ]; then
            echo
            echo "# suspend after ${SUSPEND}m (AC-aware — see idle.conf)"
            echo "listener {"
            echo "    timeout = $((SUSPEND * 60))"
            echo "    on-timeout = $SELF maybe-suspend"
            echo "}"
        fi
    } > "$OUT"
}

restart_hypridle() {
    if command -v hyprctl >/dev/null 2>&1 && hyprctl monitors >/dev/null 2>&1; then
        pkill -x hypridle 2>/dev/null || true
        hyprctl dispatch exec hypridle >/dev/null 2>&1 || true
    elif pgrep -x hypridle >/dev/null 2>&1; then
        pkill -x hypridle 2>/dev/null || true
        setsid -f hypridle >/dev/null 2>&1 || true
    fi
    # Outside a Hyprland session and not running: leave it — hyprland.conf's
    # `exec-once = hypridle` starts it at login with the freshly written config.
}

fmt() { [ "$1" -eq 0 ] && printf 'off' || printf '%sm' "$1"; }

summary() {
    printf 'lock %s · layar %s · sleep %s%s' \
        "$(fmt "$LOCK")" "$(fmt "$SCREEN_OFF")" "$(fmt "$SUSPEND")" \
        "$([ "$SUSPEND_ON_AC" -eq 1 ] && printf ' (termasuk saat dicolok)' || printf ' (nyala terus saat dicolok)')"
}

apply() {
    # keep the ordering sane: lock ≤ screen off ≤ suspend
    [ "$SCREEN_OFF" -gt 0 ] && [ "$LOCK" -gt 0 ] && [ "$SCREEN_OFF" -lt "$LOCK" ] && SCREEN_OFF="$LOCK"
    [ "$SUSPEND" -gt 0 ] && [ "$SCREEN_OFF" -gt 0 ] && [ "$SUSPEND" -lt "$SCREEN_OFF" ] && SUSPEND="$SCREEN_OFF"
    save; gen; restart_hypridle
    note "$(summary)"
}

# ── AC-aware suspend ────────────────────────────────────────────────────────
on_ac() {
    local f
    for f in /sys/class/power_supply/*/online; do
        [ -r "$f" ] || continue
        [ "$(cat "$f" 2>/dev/null)" = "1" ] && return 0
    done
    return 1
}

maybe_suspend() {
    load
    if [ "$SUSPEND_ON_AC" -eq 0 ] && on_ac; then
        exit 0    # plugged in and told to stay awake
    fi
    systemctl suspend
}

# ── presets ─────────────────────────────────────────────────────────────────
preset() {
    case "$1" in
        santai)   LOCK=45; SCREEN_OFF=47; SUSPEND=90 ;;
        normal)   LOCK=30; SCREEN_OFF=32; SUSPEND=50 ;;
        hemat)    LOCK=5;  SCREEN_OFF=6;  SUSPEND=15 ;;
        nonton)   LOCK=0;  SCREEN_OFF=0;  SUSPEND=0  ;;
        *) return 1 ;;
    esac
}

# ── wofi GUI ────────────────────────────────────────────────────────────────
menu() {
    load
    local ac_label
    if [ "$SUSPEND_ON_AC" -eq 1 ]; then
        ac_label="󰚥  Saat dicolok: ikut sleep  →  ubah jadi nyala terus"
    else
        ac_label="󰚥  Saat dicolok: nyala terus  →  ubah jadi ikut sleep"
    fi

    local options="󰒲  Sleep sekarang
󰤄  Nonton / presentasi — semua timer mati
󰾪  Santai — lock 45m · sleep 90m
󰅶  Normal — lock 30m · sleep 50m
󰂃  Hemat baterai — lock 5m · sleep 15m
$ac_label
  Ubah manual…
  Status: $(summary)"

    local choice
    choice=$(printf '%s' "$options" | wofi --dmenu --width 460 --height 320 --prompt "Sleep & Idle")
    [ -n "$choice" ] || exit 0

    case "$choice" in
        *"Sleep sekarang"*)    systemctl suspend ;;
        *"Nonton"*)            preset nonton; apply ;;
        *"Santai"*)            preset santai; apply ;;
        *"Normal"*)            preset normal; apply ;;
        *"Hemat baterai"*)     preset hemat;  apply ;;
        *"Saat dicolok"*)      SUSPEND_ON_AC=$((1 - SUSPEND_ON_AC)); apply ;;
        *"Ubah manual"*)       alacritty --class alacritty-float -e "$SELF" tui ;;
        *"Status"*)            note "$(summary)" ;;
    esac
}

# ── terminal UI ─────────────────────────────────────────────────────────────
tui() {
    load
    local B=$'\e[1m' R=$'\e[1;31m' D=$'\e[38;5;245m' N=$'\e[0m'
    local ans

    ask() { # ask <label> <current> -> echoes new value
        local label="$1" cur="$2" v
        while true; do
            read -r -p "$(printf '%s  %-34s%s[%s]%s: ' "$B" "$label" "$D" "$cur" "$N")" v
            [ -z "$v" ] && { printf '%s' "$cur"; return; }
            case "$v" in
                off|OFF|o) printf '0'; return ;;
            esac
            if is_num "$v"; then printf '%s' "$v"; return; fi
            printf '%s    angka menit, atau "off"%s\n' "$R" "$N" >&2
        done
    }

    printf '\n%s  ╭──────────────────────────────────────────────╮%s\n' "$R" "$N"
    printf '%s  │        SLEEP & IDLE  —  atur timer           │%s\n' "$R" "$N"
    printf '%s  ╰──────────────────────────────────────────────╯%s\n\n' "$R" "$N"
    printf '%s  Isi dalam MENIT. Enter = biarkan. Ketik "off" untuk mematikan.%s\n\n' "$D" "$N"

    LOCK=$(ask "Kunci layar setelah"      "$LOCK")
    SCREEN_OFF=$(ask "Matikan layar setelah" "$SCREEN_OFF")
    SUSPEND=$(ask "Sleep / suspend setelah" "$SUSPEND")

    printf '\n'
    read -r -p "$(printf '%s  Ikut sleep saat dicolok charger? (y/N)%s: ' "$B" "$N")" ans
    case "$ans" in [yY]*) SUSPEND_ON_AC=1 ;; *) SUSPEND_ON_AC=0 ;; esac

    apply
    printf '\n%s  ✓ Tersimpan:%s %s\n\n' "$R" "$N" "$(summary)"
    printf '%s  Tekan ENTER untuk menutup…%s' "$D" "$N"; read -r _
}

# ── entry point ─────────────────────────────────────────────────────────────
case "${1:-menu}" in
    menu)          menu ;;
    tui)           tui ;;
    apply)         load; apply ;;
    status)        load; printf '%s\n' "$(summary)" ;;
    maybe-suspend) maybe_suspend ;;
    set)
        load
        key="${2:-}"; val="${3:-}"
        case "$key" in
            LOCK|SCREEN_OFF|SUSPEND|SUSPEND_ON_AC)
                is_num "$val" || { echo "nilai harus angka" >&2; exit 1; }
                printf -v "$key" '%s' "$val"; apply ;;
            *) echo "key: LOCK | SCREEN_OFF | SUSPEND | SUSPEND_ON_AC" >&2; exit 1 ;;
        esac ;;
    preset)
        load; preset "${2:-}" || { echo "preset: santai | normal | hemat | nonton" >&2; exit 1; }; apply ;;
    *)
        sed -n '2,16p' "$(readlink -f "${BASH_SOURCE[0]}")" | sed 's/^# \{0,1\}//' ;;
esac
